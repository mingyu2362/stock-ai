def news_terms(name):
    """종목명으로 뉴스 검색·필터에 쓸 이름 목록을 만든다."""
    terms = [name] + NEWS_ALIASES.get(name, [])
    for suffix in ("지주", "홀딩스"):
        if name.endswith(suffix) and len(name) > len(suffix) + 1:
            terms.append(name[: -len(suffix)])
    return list(dict.fromkeys(terms))
